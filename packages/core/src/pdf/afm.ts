/** WinAnsi's codes 128–159, by the Unicode character each stands for (0: none). */
const HIGH = [0x20ac, 0, 0x201a, 0x192, 0x201e, 0x2026, 0x2020, 0x2021, 0x2c6, 0x2030, 0x160, 0x2039, 0x152, 0, 0x17d, 0, 0, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2013, 0x2014, 0x2dc, 0x2122, 0x161, 0x203a, 0x153, 0, 0x17e, 0x178];

/** A character's WinAnsi code, or 0 when the set has none. */
export const winAnsi = (cp: number): number => {
  if (cp < 256) return (cp >= 32 && cp < 127) || cp >= 160 ? cp : 0;
  const k = HIGH.indexOf(cp);
  return k < 0 ? 0 : k + 128;
};
